#!/usr/bin/env python3
"""Render results/*.json into results/results.md (one table per direction)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"


def main() -> None:
    rows = []
    for path in sorted(RESULTS.glob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        rows.append(payload)
    if not rows:
        print("no results yet - run eval/run_eval.py first")
        return

    lines = ["# Indonesian <-> English benchmark results", "",
             "Generated by `python3 eval/summarize.py` from `results/*.json`.", "",
             "chrF/chrF++/BLEU are corpus-level, 0-100 "
             "(higher is better); `metric backend` says whether sacrebleu or the "
             "bundled fallback produced the numbers.", ""]
    for direction in sorted({f"{r['src']}->{r['tgt']}" for r in rows}):
        subset = [r for r in rows if f"{r['src']}->{r['tgt']}" == direction]
        subset.sort(key=lambda r: r["metrics"]["chrf"], reverse=True)
        lines += [f"## {direction}", "",
                  "| model | prompt | pairs | chrF | chrF++ | BLEU | s/sentence | metrics | file |",
                  "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- |"]
        for r in subset:
            m = r["metrics"]
            lines.append(
                f"| `{r['model']}` | {r['prompt_style']} | {r['pairs']} | **{m['chrf']}** | "
                f"{m['chrfpp']} | {m['bleu']} | {r['seconds_per_sentence']} | "
                f"{r['metric_backend']} | `{r['label']}.json` |"
            )
        lines.append("")

        best = subset[0]
        lines += [f"### Weakest categories for the best {direction} run ({best['label']})", "",
                  "| category | avg chrF |", "| --- | ---: |"]
        for cat, score in sorted(best["chrF_by_category"].items(), key=lambda kv: kv[1]):
            lines.append(f"| {cat} | {score} |")
        lines.append("")

    (RESULTS / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'results.md'} ({len(rows)} result files)")


if __name__ == "__main__":
    main()
